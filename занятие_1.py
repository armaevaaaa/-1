# Знакомство с героем
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print("Ты входишь в больницу. Здесь темно и пахнет сыростью.")
print()

# Меню действий
options = {
    "1": f"{hero_name} медленно осматривается. В полумраке видны облупившиеся стены и старые каталки.",
    "2": f"{hero_name} осторожно шагает вперёд. Пол скрипит под ногами, а из темноты доносятся странные шорохи.",
    "3": f"{hero_name} присаживается на край стула, чтобы перевести дух. Сердце колотится где-то в горле.",
    "4": (
        f"{hero_name} замирает. Он достаёт из левого кармана фонарь, "
        "аккуратно снимает пломбу и нажимает кнопку.\n"
        "Луч света вырывается из линзы, разрезая тьму. Теперь видно, что коридор тянется куда-то вглубь здания."
    ),
    "5": f"{hero_name} подходит к приёмной стойке. На поверхности толстый слой пыли, а под ним — какие-то бумаги."
}

print("Что делаешь?")
for key, _ in options.items():
    # Формируем описание пункта динамически: ищем текст и берём первое предложение до точки
    desc = options[key].split(".")[0] + "."
    print(f"{key} - {desc}")

print()
choice = input().strip()
print()

# Обработка выбора
response = options.get(choice)
if response:
    print(response)
else:
    print("Такого варианта нет. Попробуй выбрать цифру от 1 до 5.")

